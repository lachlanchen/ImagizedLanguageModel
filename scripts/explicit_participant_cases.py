# The singer appears first in the wording of question 1 in scene 8.
REVERSED_QUESTIONS = {7}
NAMES = (("江映","余青"),("宋瑶","荀宁"),("袁汐","郭颖"),("杜蘅","任秋"),
         ("許舟","葉清"),("顧寧","羅鈞"),("邵芸","溫衡"),("李桐","簡川"))


def cases():
    for scene,(text,q1,q2) in enumerate(SCENES):
        names=NAMES[scene%len(NAMES)]
        for a,b in (names,names[::-1]):
            expected=(b,a) if scene in REVERSED_QUESTIONS else (a,b)
            for question,answer in zip((q1,q2),expected,strict=True):
                assert a not in question and b not in question
                yield text.format(a=a,b=b),question,answer
